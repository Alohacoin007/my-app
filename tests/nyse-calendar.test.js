// Alpexa — NYSE 세션 달력 (RED→GREEN). 2026-09-07 노동절 오탐에서 나옴.
//
// 자가검진의 주식 라이브니스 검사가 "장중"을 **UTC 13:35~19:55 · 평일**로만 판정해서
//   ① 노동절(9/7)에 "WS 펌프 퇴행 의심" 경고를 두 번 띄웠다 — 값이 완전히 고정된 걸
//      실측했으니 펌프가 아니라 **휴장**이었다.
//   ② 서머타임이 끝나는 11~3월엔 UTC 고정 창이 한 시간 어긋난다 — 프리마켓 55분을
//      장중으로 보고 마지막 1시간(15:00~16:00 ET)을 놓친다.
// 둘 다 "시장 달력을 모른다"는 한 클래스. 뉴욕 현지시간 + 휴장일 + 조기폐장으로 닫는다.
//
// ⚠️ 오탐 체크는 무시당해 더 해롭다(CLAUDE.md). 그래서 이 달력은 **규칙 기반**이다 —
//    날짜를 하드코딩하면 내년에 썩는다. NYSE 규정: 1/1(토→관측 없음, 일→월) · MLK 1월 셋째 월 ·
//    대통령의날 2월 셋째 월 · 성금요일 · 현충일 5월 마지막 월 · 준틴스 6/19 · 독립기념일 7/4 ·
//    노동절 9월 첫째 월 · 추수감사절 11월 넷째 목 · 성탄절 12/25 (토→금, 일→월 관측).
//    조기폐장(13:00 ET): 7/3(평일일 때) · 추수감사절 다음날 · 12/24(평일일 때).
'use strict';
let pass = true;
const ok = (n, c) => { if (!c) pass = false; console.log(`  ${c ? '✅' : '❌'} ${n}`); };

const cal = require('./nyse-calendar');
const at = (iso) => new Date(iso);
const closed = (iso, why) => { const s = cal.nyseSession(at(iso)); ok(`${iso}  ${why} → 휴장 (${s.reason})`, s.open === false); };
const open = (iso, why) => { const s = cal.nyseSession(at(iso)); ok(`${iso}  ${why} → 장중`, s.open === true); };

console.log('\n=== RED→GREEN: 2026-09-07 노동절 (실제 오탐 건) ===');
closed('2026-09-07T15:26:00Z', '노동절 · 11:26 ET');
closed('2026-09-07T18:26:00Z', '노동절 · 14:26 ET');
open('2026-09-08T15:26:00Z', '다음날 화요일 · 11:26 ET');

console.log('\n=== 휴장일 규칙 (2026) ===');
closed('2026-01-01T15:00:00Z', '신정(목)');
closed('2026-01-19T15:00:00Z', 'MLK 1월 셋째 월');
closed('2026-02-16T15:00:00Z', '대통령의 날 2월 셋째 월');
closed('2026-04-03T15:00:00Z', '성금요일 (부활절 4/5)');
closed('2026-05-25T15:00:00Z', '현충일 5월 마지막 월');
closed('2026-06-19T15:00:00Z', '준틴스(금)');
closed('2026-07-03T15:00:00Z', '독립기념일 7/4(토) → 금 관측');
closed('2026-11-26T16:00:00Z', '추수감사절 11월 넷째 목');
closed('2026-12-25T16:00:00Z', '성탄절(금)');
open('2026-07-06T15:00:00Z', '7/6 월 — 관측일 다음 평일');
open('2026-04-02T15:00:00Z', '성목요일 — 성금요일 전날은 정상 장');

console.log('\n=== 관측일 규칙 ===');
closed('2027-01-01T16:00:00Z', '2027 신정(금)');
closed('2027-12-24T16:00:00Z', '2027 성탄절 12/25(토) → 12/24 금 관측');
closed('2028-01-17T16:00:00Z', '2028 MLK');
open('2027-12-31T16:00:00Z', '2027-12-31 금 — 2028 신정이 토요일이면 전날 휴장 없음 (NYSE 특칙)');

console.log('\n=== 조기폐장 13:00 ET ===');
open('2026-11-27T15:00:00Z', '추수감사절 다음날 10:00 ET');
closed('2026-11-27T18:30:00Z', '추수감사절 다음날 13:30 ET — 조기폐장 후');
closed('2026-12-24T18:30:00Z', '12/24(목) 13:30 ET — 조기폐장 후');
open('2027-07-02T18:30:00Z', '2027-07-02(금) 14:30 ET — 7/4 가 일요일이라 7/5 월 관측; 7/2 는 조기폐장 아님');
closed('2027-07-05T16:00:00Z', '2027-07-05(월) — 독립기념일 관측');

console.log('\n=== 서머타임 — UTC 고정 창의 구멍 ===');
open('2026-01-20T15:00:00Z', '1월(EST) 10:00 ET — 옛 UTC 창에서도 장중');
closed('2026-01-20T13:40:00Z', '1월(EST) 08:40 ET — 프리마켓. 옛 UTC 창은 이걸 장중으로 봤다');
open('2026-01-20T20:30:00Z', '1월(EST) 15:30 ET — 옛 UTC 창은 이걸 장외로 봤다');
open('2026-07-20T13:40:00Z', '7월(EDT) 09:40 ET — 장중');
closed('2026-07-20T20:30:00Z', '7월(EDT) 16:30 ET — 폐장 후');

console.log('\n=== 주말 ===');
closed('2026-09-05T15:00:00Z', '토');
closed('2026-09-06T15:00:00Z', '일');

// ── 락스텝: 자가검진이 이 달력을 실제로 쓰는가 (안 쓰면 이 테스트는 장식이다)
const fs = require('fs'), path = require('path');
const SC = fs.readFileSync(path.join(__dirname, 'daily-selfcheck.js'), 'utf8');
console.log('\n=== 락스텝: daily-selfcheck 가 달력을 쓴다 ===');
ok('require("./nyse-calendar") 가 있다', /require\(['"]\.\/nyse-calendar['"]\)/.test(SC));
ok('nyseSession( 을 호출한다', /nyseSession\(/.test(SC));
ok('옛 UTC 고정 창(13 * 60 + 35)이 사라졌다', !/13 \* 60 \+ 35/.test(SC));

console.log('\n' + (pass ? '🟢 NYSE 달력이 휴장·조기폐장·서머타임을 안다' : '🔴 달력 깨짐') + '\n');
process.exit(pass ? 0 : 1);
